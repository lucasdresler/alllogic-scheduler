def admin_concluir_primeiro_acesso(
    conn,
    usuario_atual,
    novo_login,
    nova_senha,
    email,
    nome_responsavel,
    nome_estabelecimento,
):
    """Conclui a configuração inicial do primeiro acesso de forma atômica."""
    from werkzeug.security import generate_password_hash

    row = conn.execute(
        "SELECT id, usuario, senha_hash, senha_inicial_alterada FROM admin WHERE usuario = %s",
        (usuario_atual,),
    ).fetchone()
    if not row:
        return False, "Usuário não encontrado."

    # Verifica se novo_login já está em uso por outro registro
    login_existente = conn.execute(
        "SELECT id FROM admin WHERE LOWER(usuario) = LOWER(%s) AND id != %s",
        (novo_login, row["id"]),
    ).fetchone()
    if login_existente:
        return False, "O login informado já está em uso."

    novo_hash = generate_password_hash(nova_senha)

    conn.execute(
        """
        UPDATE admin
        SET usuario = %s,
            senha_hash = %s,
            senha_inicial_alterada = TRUE,
            email = %s,
            nome_responsavel = %s
        WHERE id = %s
        """,
        (novo_login, novo_hash, email, nome_responsavel, row["id"]),
    )

    atualizar_configuracao(conn, "nome_estabelecimento", nome_estabelecimento)

    return True, None


def admin_alterar_senha(conn, usuario, senha_atual, nova_senha):
    """Altera a senha do admin validando a senha atual."""
    from werkzeug.security import check_password_hash, generate_password_hash

    row = conn.execute(
        "SELECT id, senha_hash, senha_inicial_alterada FROM admin WHERE usuario = %s",
        (usuario,),
    ).fetchone()
    if not row:
        return False, "Usuário não encontrado."

    if not check_password_hash(row["senha_hash"], senha_atual):
        return False, "Senha atual incorreta."

    if senha_atual == nova_senha:
        return False, "A nova senha deve ser diferente da senha atual."

    novo_hash = generate_password_hash(nova_senha)
    conn.execute(
        """
        UPDATE admin
        SET senha_hash = %s, senha_inicial_alterada = TRUE
        WHERE id = %s
        """,
        (novo_hash, row["id"]),
    )
    return True, None



def obter_configuracao(conn, chave):
    """Obtém um valor de configuração do banco."""
    row = conn.execute(
        "SELECT valor FROM configuracao WHERE chave = %s", (chave,)
    ).fetchone()
    return row["valor"] if row else None


def obter_todas_configuracoes(conn):
    """Obtém todas as configurações como dicionário."""
    rows = conn.execute("SELECT chave, valor FROM configuracao").fetchall()
    return {row["chave"]: row["valor"] for row in rows}


def atualizar_configuracao(conn, chave, valor):
    """Atualiza ou insere uma configuração."""
    conn.execute(
        """
        INSERT INTO configuracao (chave, valor) VALUES (%s, %s)
        ON CONFLICT (chave) DO UPDATE SET valor = EXCLUDED.valor
        """,
        (chave, valor),
    )
    _incrementar_versao_configuracoes(conn)


def atualizar_configuracoes(conn, configuracoes):
    """Atualiza múltiplas configurações de uma vez."""
    with conn.cursor() as cur:
        cur.executemany(
            """
            INSERT INTO configuracao (chave, valor) VALUES (%s, %s)
            ON CONFLICT (chave) DO UPDATE SET valor = EXCLUDED.valor
            """,
            list(configuracoes.items()),
        )
    _incrementar_versao_configuracoes(conn)


def _incrementar_versao_configuracoes(conn):
    conn.execute(
        """
        INSERT INTO configuracao (chave, valor)
        VALUES (%s, '1')
        ON CONFLICT (chave) DO UPDATE
        SET valor = (configuracao.valor::BIGINT + 1)::TEXT
        """,
        (CONFIG_CACHE_VERSION_KEY,),
    )


def admin_precisa_alterar_senha(conn, usuario):
    """Verifica se o admin precisa concluir a configuração inicial (primeiro acesso)."""
    row = conn.execute(
        "SELECT usuario, senha_inicial_alterada, email, nome_responsavel FROM admin WHERE usuario = %s",
        (usuario,),
    ).fetchone()
    if not row:
        return False
    email = (row["email"] or "").strip() if "email" in row and row["email"] else ""
    nome_responsavel = (
        (row["nome_responsavel"] or "").strip()
        if "nome_responsavel" in row and row["nome_responsavel"]
        else ""
    )
    return (
        (not row["senha_inicial_alterada"])
        or (not email)
        or (not nome_responsavel)
        or (row["usuario"] == "admin")
    )


def admin_concluir_primeiro_acesso(
    conn,
    usuario_atual,
    novo_login,
    nova_senha,
    email,
    nome_responsavel,
    nome_estabelecimento,
):
    """Conclui a configuração inicial do primeiro acesso de forma atômica."""
    from werkzeug.security import generate_password_hash

    row = conn.execute(
        "SELECT id, usuario, senha_hash, senha_inicial_alterada FROM admin WHERE usuario = %s",
        (usuario_atual,),
    ).fetchone()
    if not row:
        return False, "Usuário não encontrado."

    # Verifica se novo_login já está em uso por outro registro
    login_existente = conn.execute(
        "SELECT id FROM admin WHERE LOWER(usuario) = LOWER(%s) AND id != %s",
        (novo_login, row["id"]),
    ).fetchone()
    if login_existente:
        return False, "O login informado já está em uso."

    novo_hash = generate_password_hash(nova_senha)

    conn.execute(
        """
        UPDATE admin
        SET usuario = %s,
            senha_hash = %s,
            senha_inicial_alterada = TRUE,
            email = %s,
            nome_responsavel = %s
        WHERE id = %s
        """,
        (novo_login, novo_hash, email, nome_responsavel, row["id"]),
    )

    atualizar_configuracao(conn, "nome_estabelecimento", nome_estabelecimento)

    return True, None


def admin_alterar_senha(conn, usuario, senha_atual, nova_senha):
    """Altera a senha do admin validando a senha atual."""
    from werkzeug.security import check_password_hash, generate_password_hash

    row = conn.execute(
        "SELECT id, senha_hash, senha_inicial_alterada FROM admin WHERE usuario = %s",
        (usuario,),
    ).fetchone()
    if not row:
        return False, "Usuário não encontrado."

    if not check_password_hash(row["senha_hash"], senha_atual):
        return False, "Senha atual incorreta."

    if senha_atual == nova_senha:
        return False, "A nova senha deve ser diferente da senha atual."

    novo_hash = generate_password_hash(nova_senha)
    conn.execute(
        """
        UPDATE admin
        SET senha_hash = %s, senha_inicial_alterada = TRUE
        WHERE id = %s
        """,
        (novo_hash, row["id"]),
    )
    return True, None


def obter_admin_por_email(conn, email):
    """Busca admin pelo e-mail de recuperação cadastrado na conta."""
    if not email:
        return None
    return conn.execute(
        "SELECT id, usuario, email, nome_responsavel FROM admin WHERE LOWER(email) = LOWER(%s)",
        (email.strip(),),
    ).fetchone()


def criar_token_recuperacao(conn, admin_id, token_hash, expira_em):
    """Salva o hash do token de recuperação com prazo de expiração de 30 min."""
    conn.execute(
        """
        INSERT INTO admin_token_recuperacao (admin_id, token_hash, expira_em, usado)
        VALUES (%s, %s, %s, FALSE)
        """,
        (admin_id, token_hash, expira_em),
    )


def validar_token_recuperacao(conn, token_hash):
    """Valida se o token de recuperação existe, não foi usado e não expirou."""
    from datetime import datetime, timezone

    row = conn.execute(
        """
        SELECT t.id, t.admin_id, t.expira_em, t.usado, a.usuario, a.email
        FROM admin_token_recuperacao t
        JOIN admin a ON a.id = t.admin_id
        WHERE t.token_hash = %s
        """,
        (token_hash,),
    ).fetchone()

    if not row:
        return False, "Link de recuperação inválido.", None

    if row["usado"]:
        return False, "Este link de recuperação já foi utilizado.", None

    agora = datetime.now(timezone.utc)
    expira_em = row["expira_em"]
    if expira_em.tzinfo is None:
        expira_em = expira_em.replace(tzinfo=timezone.utc)

    if expira_em < agora:
        return False, "Este link de recuperação expirou.", None

    return True, None, row


def redefinir_senha_com_token(conn, token_hash, nova_senha):
    """Redefine a senha do admin e invalida o token de uso único de forma atômica."""
    from werkzeug.security import generate_password_hash

    valido, erro, row = validar_token_recuperacao(conn, token_hash)
    if not valido:
        return False, erro

    novo_hash = generate_password_hash(nova_senha)

    conn.execute(
        "UPDATE admin_token_recuperacao SET usado = TRUE WHERE id = %s",
        (row["id"],),
    )
    conn.execute(
        "UPDATE admin SET senha_hash = %s, senha_inicial_alterada = TRUE WHERE id = %s",
        (novo_hash, row["admin_id"]),
    )
    return True, None


def atualizar_agendamentos_realizados(conn):
    conn.execute(
        """
        UPDATE agendamento
        SET status = 'realizado'
        WHERE status = 'agendado'
          AND data::date < CURRENT_DATE
        """
    )


def seed_data(conn):
    count_servicos = conn.execute(
        "SELECT COUNT(*) AS c FROM servico"
    ).fetchone()["c"]

    if count_servicos == 0:
        with conn.cursor() as cur:
            cur.executemany(
                "INSERT INTO servico (nome, preco, duracao_minutos) VALUES (%s, %s, %s)",
                [
                    ("Corte", 40.0, 30),
                    ("Barba", 35.0, 30),
                    ("Corte + Barba", 70.0, 60),
                ],
            )

    count_profissionais = conn.execute(
        "SELECT COUNT(*) AS c FROM profissional"
    ).fetchone()["c"]

    if count_profissionais == 0:
        with conn.cursor() as cur:
            cur.executemany(
                "INSERT INTO profissional (nome, ativo) VALUES (%s, TRUE)",
                [("Carlos",), ("Rafael",)],
            )

    count_admin = conn.execute(
        "SELECT COUNT(*) AS c FROM admin"
    ).fetchone()["c"]

    if count_admin == 0:
        from werkzeug.security import generate_password_hash

        senha_inicial = os.environ.get("ADMIN_SENHA_INICIAL")
        if not senha_inicial:
            raise RuntimeError(
                "ADMIN_SENHA_INICIAL não definida. "
                "Defina a variável de ambiente ADMIN_SENHA_INICIAL para criar o usuário admin inicial."
            )
        conn.execute(
            "INSERT INTO admin (usuario, senha_hash, senha_inicial_alterada) VALUES (%s, %s, FALSE)",
            ("admin", generate_password_hash(senha_inicial)),
        )

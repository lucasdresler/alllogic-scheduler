def obter_configuracao(conn, chave):
    """Obtém um valor de configuração do banco."""
    row = conn.execute(
        "SELECT valor FROM configuracao WHERE chave = %s", (chave,)
    ).fetchone()
    return row["valor"] if row else None


def obter_todas_configuracoes(conn):
    """Obtém todas as configurações como dicionário."""
    rows = conn.execute("SELECT chave, valor FROM configuracao").fetchall()
    return {row["chave"]: row["valor"] for row in rows}


def atualizar_configuracao(conn, chave, valor):
    """Atualiza ou insere uma configuração."""
    conn.execute(
        """
        INSERT INTO configuracao (chave, valor) VALUES (%s, %s)
        ON CONFLICT (chave) DO UPDATE SET valor = EXCLUDED.valor
        """,
        (chave, valor),
    )


def atualizar_configuracoes(conn, configuracoes):
    """Atualiza múltiplas configurações de uma vez."""
    with conn.cursor() as cur:
        cur.executemany(
            """
            INSERT INTO configuracao (chave, valor) VALUES (%s, %s)
            ON CONFLICT (chave) DO UPDATE SET valor = EXCLUDED.valor
            """,
            list(configuracoes.items()),
        )


def admin_precisa_alterar_senha(conn, usuario):
    """Verifica se o admin precisa alterar a senha inicial (primeiro acesso)."""
    row = conn.execute(
        "SELECT senha_inicial_alterada FROM admin WHERE usuario = %s", (usuario,)
    ).fetchone()
    if not row:
        return False
    return not row["senha_inicial_alterada"]


def admin_alterar_senha(conn, usuario, senha_atual, nova_senha):
    """Altera a senha do admin validando a senha atual."""
    from werkzeug.security import check_password_hash, generate_password_hash

    row = conn.execute(
        "SELECT senha_hash, senha_inicial_alterada FROM admin WHERE usuario = %s", (usuario,)
    ).fetchone()
    if not row:
        return False, "Usuário não encontrado."

    if not check_password_hash(row["senha_hash"], senha_atual):
        return False, "Senha atual incorreta."

    novo_hash = generate_password_hash(nova_senha)
    conn.execute(
        "UPDATE admin SET senha_hash = %s, senha_inicial_alterada = TRUE WHERE usuario = %s",
        (novo_hash, usuario),
    )
    return True, None


def atualizar_agendamentos_realizados(conn):
    conn.execute(
        """
        UPDATE agendamento
        SET status = 'realizado'
        WHERE status = 'agendado'
          AND data::date < CURRENT_DATE
        """
    )


def seed_data(conn):
    count_servicos = conn.execute(
        "SELECT COUNT(*) AS c FROM servico"
    ).fetchone()["c"]

    if count_servicos == 0:
        with conn.cursor() as cur:
            cur.executemany(
                "INSERT INTO servico (nome, preco, duracao_minutos) VALUES (%s, %s, %s)",
                [
                    ("Corte", 40.0, 30),
                    ("Barba", 35.0, 30),
                    ("Corte + Barba", 70.0, 60),
                ],
            )

    count_profissionais = conn.execute(
        "SELECT COUNT(*) AS c FROM profissional"
    ).fetchone()["c"]

    if count_profissionais == 0:
        with conn.cursor() as cur:
            cur.executemany(
                "INSERT INTO profissional (nome, ativo) VALUES (%s, TRUE)",
                [("Carlos",), ("Rafael",)],
            )

    count_admin = conn.execute(
        "SELECT COUNT(*) AS c FROM admin"
    ).fetchone()["c"]

    if count_admin == 0:
        from werkzeug.security import generate_password_hash

        senha_inicial = os.environ.get("ADMIN_SENHA_INICIAL")
        if not senha_inicial:
            raise RuntimeError(
                "ADMIN_SENHA_INICIAL não definida. "
                "Defina a variável de ambiente ADMIN_SENHA_INICIAL para criar o usuário admin inicial."
            )
        conn.execute(
            "INSERT INTO admin (usuario, senha_hash, senha_inicial_alterada) VALUES (%s, %s, FALSE)",
            ("admin", generate_password_hash(senha_inicial)),
        )

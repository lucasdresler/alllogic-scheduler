import os
from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row

CONFIG_CACHE_VERSION_KEY = "__config_generation__"


def get_connection():
    return psycopg.connect(
        host=os.environ["POSTGRES_HOST"],
        port=os.environ["POSTGRES_PORT"],
        dbname=os.environ["POSTGRES_DB"],
        user=os.environ["POSTGRES_USER"],
        password=os.environ["POSTGRES_PASSWORD"],
        row_factory=dict_row,
    )


@contextmanager
def db_session():
    conn = get_connection()
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db():
    with db_session() as conn:
        # Serializa a inicialização para evitar corrida entre workers.
        conn.execute("SELECT pg_advisory_lock(314159265358979)")
        conn.execute("""
            CREATE TABLE IF NOT EXISTS configuracao (
                chave TEXT PRIMARY KEY,
                valor TEXT NOT NULL
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS servico (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nome TEXT NOT NULL,
                descricao TEXT NOT NULL DEFAULT '',
                preco NUMERIC(10, 2) NOT NULL,
                duracao_minutos INTEGER NOT NULL,
                ativo BOOLEAN NOT NULL DEFAULT TRUE
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS profissional (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nome TEXT NOT NULL,
                ativo BOOLEAN NOT NULL DEFAULT TRUE
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS profissional_servico (
                profissional_id INTEGER NOT NULL,
                servico_id INTEGER NOT NULL,
                PRIMARY KEY (profissional_id, servico_id),
                FOREIGN KEY (profissional_id) REFERENCES profissional(id) ON DELETE CASCADE,
                FOREIGN KEY (servico_id) REFERENCES servico(id) ON DELETE CASCADE
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS agendamento (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                cliente_nome TEXT NOT NULL,
                cliente_telefone TEXT NOT NULL,
                servico_id INTEGER NOT NULL,
                profissional_id INTEGER NOT NULL,
                data TEXT NOT NULL,
                hora TEXT NOT NULL,
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                profissional_nome_snapshot TEXT,
                FOREIGN KEY (servico_id) REFERENCES servico(id),
                FOREIGN KEY (profissional_id) REFERENCES profissional(id)
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS agendamento_servico (
                agendamento_id INTEGER NOT NULL,
                servico_id INTEGER NOT NULL,
                nome_servico TEXT,
                preco_unitario NUMERIC(10, 2),
                duracao_minutos INTEGER,
                PRIMARY KEY (agendamento_id, servico_id),
                FOREIGN KEY (agendamento_id) REFERENCES agendamento(id) ON DELETE CASCADE,
                FOREIGN KEY (servico_id) REFERENCES servico(id)
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS admin (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario TEXT NOT NULL UNIQUE,
                senha_hash TEXT NOT NULL,
                senha_inicial_alterada BOOLEAN NOT NULL DEFAULT FALSE,
                email TEXT,
                nome_responsavel TEXT
            )
        """)

        # Compatibilidade com bancos existentes: adiciona o status sem perder dados.
        conn.execute("""
            ALTER TABLE agendamento
            ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'agendado'
        """)

        # Compatibilidade: adiciona coluna senha_inicial_alterada se não existir.
        conn.execute("""
            ALTER TABLE admin
            ADD COLUMN IF NOT EXISTS senha_inicial_alterada BOOLEAN NOT NULL DEFAULT FALSE
        """)

        # Compatibilidade: adiciona coluna email em admin se não existir.
        conn.execute("""
            ALTER TABLE admin
            ADD COLUMN IF NOT EXISTS email TEXT
        """)

        # Compatibilidade: adiciona coluna nome_responsavel em admin se não existir.
        conn.execute("""
            ALTER TABLE admin
            ADD COLUMN IF NOT EXISTS nome_responsavel TEXT
        """)

        # Tabela de tokens de recuperação de senha (expiráveis e uso único)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS admin_token_recuperacao (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                admin_id INTEGER NOT NULL REFERENCES admin(id) ON DELETE CASCADE,
                token_hash TEXT NOT NULL UNIQUE,
                expira_em TIMESTAMP WITH TIME ZONE NOT NULL,
                usado BOOLEAN NOT NULL DEFAULT FALSE,
                criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        # Compatibilidade: adiciona coluna ativo em servico se não existir.
        conn.execute("""
            ALTER TABLE servico
            ADD COLUMN IF NOT EXISTS ativo BOOLEAN NOT NULL DEFAULT TRUE
        """)

        conn.execute("""
            ALTER TABLE servico
            ADD COLUMN IF NOT EXISTS descricao TEXT NOT NULL DEFAULT ''
        """)

        conn.execute("""
            ALTER TABLE agendamento
            ADD COLUMN IF NOT EXISTS profissional_nome_snapshot TEXT
        """)

        conn.execute("""
            ALTER TABLE agendamento_servico
            ADD COLUMN IF NOT EXISTS nome_servico TEXT
        """)
        conn.execute("""
            ALTER TABLE agendamento_servico
            ADD COLUMN IF NOT EXISTS preco_unitario NUMERIC(10, 2)
        """)
        conn.execute("""
            ALTER TABLE agendamento_servico
            ADD COLUMN IF NOT EXISTS duracao_minutos INTEGER
        """)

        conn.execute("""
            UPDATE agendamento_servico AS ags
            SET nome_servico = COALESCE(ags.nome_servico, s.nome),
                preco_unitario = COALESCE(ags.preco_unitario, s.preco),
                duracao_minutos = COALESCE(ags.duracao_minutos, s.duracao_minutos)
            FROM servico AS s
            WHERE s.id = ags.servico_id
              AND (
                  ags.nome_servico IS NULL
                  OR ags.preco_unitario IS NULL
                  OR ags.duracao_minutos IS NULL
              )
        """)

        conn.execute("""
            UPDATE agendamento AS a
            SET profissional_nome_snapshot = p.nome
            FROM profissional AS p
            WHERE p.id = a.profissional_id
              AND a.profissional_nome_snapshot IS NULL
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_agendamento_profissional_data_status
            ON agendamento (profissional_id, data, status)
        """)

        # Migra a relação legada de serviço único para a nova relação.
        conn.execute("""
            INSERT INTO agendamento_servico (agendamento_id, servico_id)
            SELECT id, servico_id
            FROM agendamento
            WHERE servico_id IS NOT NULL
            ON CONFLICT (agendamento_id, servico_id) DO NOTHING
        """)

        conn.execute("""
            UPDATE agendamento_servico AS ags
            SET nome_servico = COALESCE(ags.nome_servico, s.nome),
                preco_unitario = COALESCE(ags.preco_unitario, s.preco),
                duracao_minutos = COALESCE(ags.duracao_minutos, s.duracao_minutos)
            FROM servico AS s
            WHERE s.id = ags.servico_id
              AND (
                  ags.nome_servico IS NULL
                  OR ags.preco_unitario IS NULL
                  OR ags.duracao_minutos IS NULL
              )
        """)

        seed_configuracao_padrao(conn)
        conn.execute(
            """
            INSERT INTO configuracao (chave, valor)
            VALUES (%s, '0')
            ON CONFLICT (chave) DO NOTHING
            """,
            (CONFIG_CACHE_VERSION_KEY,),
        )
        seed_data(conn)



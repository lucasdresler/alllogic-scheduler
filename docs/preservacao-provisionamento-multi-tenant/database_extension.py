def gerar_slug(texto):
    """Gera um slug URL-friendly a partir do nome do estabelecimento."""
    texto = unicodedata.normalize("NFKD", texto).encode("ascii", "ignore").decode("ascii")
    texto = re.sub(r"[^\w\s-]", "", texto).strip().lower()
    return re.sub(r"[-\s]+", "-", texto) or "estabelecimento"


def criar_estabelecimento_com_admin(
    conn,
    nome_estabelecimento,
    nome_responsavel,
    email,
    telefone,
    usuario,
    senha_hash,
):
    """
    Cria atomicamente um novo estabelecimento com 14 dias de teste e sua conta admin vinculada.
    Garante integridade transacional completa (sem contas órfãs).
    """
    base_slug = gerar_slug(nome_estabelecimento)
    slug = base_slug
    contador = 1
    while conn.execute("SELECT 1 FROM estabelecimento WHERE slug = %s", (slug,)).fetchone():
        slug = f"{base_slug}-{contador}"
        contador += 1

    agora = datetime.now(timezone.utc)
    trial_fim = agora + timedelta(days=14)

    row_est = conn.execute(
        """
        INSERT INTO estabelecimento (
            slug, nome, nome_responsavel, email, telefone, trial_inicio, trial_fim, status
        ) VALUES (%s, %s, %s, %s, %s, %s, %s, 'ativo')
        RETURNING id, slug, nome, email, trial_inicio, trial_fim, status
        """,
        (slug, nome_estabelecimento.strip(), nome_responsavel.strip(), email.strip().lower(), telefone.strip(), agora, trial_fim),
    ).fetchone()

    estabelecimento_id = row_est["id"]

    row_admin = conn.execute(
        """
        INSERT INTO admin (
            usuario, senha_hash, senha_inicial_alterada, email, nome_responsavel, estabelecimento_id
        ) VALUES (%s, %s, TRUE, %s, %s, %s)
        RETURNING id, usuario, email
        """,
        (usuario.strip(), senha_hash, email.strip().lower(), nome_responsavel.strip(), estabelecimento_id),
    ).fetchone()

    return {
        "estabelecimento_id": estabelecimento_id,
        "admin_id": row_admin["id"],
        "slug": row_est["slug"],
        "nome": row_est["nome"],
        "email": row_est["email"],
        "trial_inicio": row_est["trial_inicio"],
        "trial_fim": row_est["trial_fim"],
        "status": row_est["status"],
    }


def obter_estabelecimento_por_id(conn, estabelecimento_id):
    """Retorna dados do estabelecimento pelo ID."""
    if not estabelecimento_id:
        return None
    return conn.execute(
        "SELECT * FROM estabelecimento WHERE id = %s", (estabelecimento_id,)
    ).fetchone()


def obter_estabelecimento_por_email(conn, email):
    """Retorna dados do estabelecimento pelo e-mail do responsável."""
    if not email:
        return None
    return conn.execute(
        "SELECT * FROM estabelecimento WHERE LOWER(email) = LOWER(%s)", (email.strip(),)
    ).fetchone()


def obter_estabelecimento_por_slug(conn, slug):
    """Retorna dados do estabelecimento pelo slug."""
    if not slug:
        return None
    return conn.execute(
        "SELECT * FROM estabelecimento WHERE slug = %s", (slug.strip().lower(),)
    ).fetchone()


def verificar_status_trial(conn, estabelecimento_id):
    """
    Verifica o estado do período de teste de 14 dias do estabelecimento.
    Se o prazo tiver expirado e o status for 'ativo', atualiza para 'expirado'.
    Retorna o status atualizado, datas de vigência e contagem de dias restantes.
    """
    if not estabelecimento_id:
        return {"status": "ativo", "expirado": False, "dias_restantes": 14}
    est = obter_estabelecimento_por_id(conn, estabelecimento_id)
    if not est:
        return {"status": "ativo", "expirado": False, "dias_restantes": 14}

    agora = datetime.now(timezone.utc)
    trial_fim = est["trial_fim"]
    status_atual = est["status"]

    if status_atual == "ativo" and agora > trial_fim:
        conn.execute(
            "UPDATE estabelecimento SET status = 'expirado' WHERE id = %s",
            (estabelecimento_id,),
        )
        status_atual = "expirado"

    delta = trial_fim - agora
    dias_restantes = max(0, delta.days if delta.total_seconds() > 0 else 0)

    return {
        "status": status_atual,
        "expirado": status_atual == "expirado",
        "trial_inicio": est["trial_inicio"],
        "trial_fim": trial_fim,
        "dias_restantes": dias_restantes,
    }


def obter_admin_com_estabelecimento(conn, usuario):
    """Retorna dados do admin e de seu respectivo estabelecimento."""
    if not usuario:
        return None
    return conn.execute(
        """
        SELECT a.*, e.nome AS estabelecimento_nome, e.slug AS estabelecimento_slug,
               e.trial_inicio, e.trial_fim, e.status AS estabelecimento_status
        FROM admin a
        LEFT JOIN estabelecimento e ON e.id = a.estabelecimento_id
        WHERE a.usuario = %s
        """,
        (usuario.strip(),),
    ).fetchone()
